//! Rust bindings for TVM IR objects, generated by `tvm-ffi-stubgen --target rust`
//! from the reflection metadata of `libtvm_compiler`.
//!
//! Each module owns one type-key namespace. The `tvm-ffi-stubgen(begin)` /
//! `tvm-ffi-stubgen(end)` blocks are regenerated in place; code outside them
//! is hand-written and never touched by the generator.
//!
//! Regenerate from the repository root after rebuilding `libtvm_compiler`
//! (add `--check` to only report stale blocks):
//!
//! ```bash
//! tvm-ffi-stubgen rust/src --target rust --dlls build/lib/libtvm_compiler.so
//! ```
//!
//! The blocks are formatted the way rustfmt formats them, so `cargo fmt --check` and
//! `tvm-ffi-stubgen --check` agree. That needs the generator of tvm-ffi `abcc398` or later, the
//! `3rdparty/tvm-ffi` this tree pins.
//!
//! Node types defined in Rust rather than mirrored from C++ derive their reflection with
//! tvm-ffi's `#[reflect]` fields; [`node`] supplies what extending a C++ IR node needs.

/// Copy-on-write edits for a complete, `#[type_final]` node, written next to its binding.
///
/// `node.with(|n| { n.a = a; n.b = b; })` is C++ `auto* n = node.CopyOnWrite(); n->a = a; ...`:
/// a copy that keeps every other field and runs no constructor logic. `node.update(...)` is the
/// same edit, except that it returns `node` itself when every field still holds what it held,
/// as a C++ mutator returns a node none of whose children changed. Each listed
/// `with_<field>(value)` replaces one field. `new(...)` names the `<Node>Obj::new` arguments in
/// order; fields of an ancestor (such as `loc`) are copied but cannot be edited.
macro_rules! impl_with_fields {
    ($node:ident, $obj:ident, new($($arg:ident),+ $(,)?), {$($method:ident: $field:ident: $ty:ty),+ $(,)?}) => {
        impl $node {
            /// A copy with the fields `edit` assigns replaced (C++ `CopyOnWrite()`).
            #[allow(clippy::clone_on_copy)]
            pub fn with(&self, edit: impl FnOnce(&mut $obj)) -> Self {
                let mut obj = $obj::new($(self.$arg.clone()),+);
                edit(&mut obj);
                Self { base: ObjectArc::new(obj) }
            }

            /// Like [`Self::with`], but `self` itself when no field changed.
            #[allow(clippy::clone_on_copy)]
            pub fn update(&self, edit: impl FnOnce(&mut $obj)) -> Self {
                let mut obj = $obj::new($(self.$arg.clone()),+);
                edit(&mut obj);
                if true $(&& $crate::SameField::same_field(&obj.$field, &self.$field))+ {
                    return self.clone();
                }
                Self { base: ObjectArc::new(obj) }
            }
            $(
                #[doc = concat!("A copy with `", stringify!($field), "` replaced.")]
                pub fn $method(&self, $field: $ty) -> Self {
                    self.with(|node| node.$field = $field)
                }
            )+
        }
    };
}

/// C++ `TVM_FFI_CHECK(condition, Kind) << message`, and `TVM_FFI_ICHECK(condition)` with
/// `INTERNAL_ERROR`: unless `condition` holds, return the error `Check failed: (<cpp>) is false:
/// <message>`. `cpp` is the condition as C++ spells it, which the message shows; `message` is a
/// format string with its arguments.
///
/// ```ignore
/// check!(!tag.is_empty(), VALUE_ERROR, "!tag->value.empty()", "expects a nonempty tag");
/// ```
macro_rules! check {
    ($condition:expr, $kind:expr, $cpp:literal $(,)?) => {
        tvm_ffi::ensure!($condition, $kind, concat!("Check failed: (", $cpp, ") is false: "))
    };
    ($condition:expr, $kind:expr, $cpp:literal, $message:literal $(, $args:expr)* $(,)?) => {
        tvm_ffi::ensure!(
            $condition,
            $kind,
            concat!("Check failed: (", $cpp, ") is false: ", $message)
            $(, $args)*
        )
    };
}

/// C++ `TVM_FFI_CHECK_EQ(lhs, rhs, Kind) << message` and the other comparisons, and their
/// `TVM_FFI_ICHECK_*` forms with `INTERNAL_ERROR`: unless `lhs <op> rhs`, return the error `Check
/// failed: <cpp> (<lhs> vs. <rhs>) : <message>`, which shows both values.
///
/// ```ignore
/// check_cmp!(indices.len(), ==, 1, INTERNAL_ERROR, "store->indices.size() == 1");
/// ```
macro_rules! check_cmp {
    ($lhs:expr, $op:tt, $rhs:expr, $kind:expr, $cpp:literal $(, $message:literal $(, $args:expr)*)? $(,)?) => {{
        let (lhs, rhs) = ($lhs, $rhs);
        tvm_ffi::ensure!(
            lhs $op rhs,
            $kind,
            concat!("Check failed: ", $cpp, " ({} vs. {}) : " $(, $message)?),
            lhs,
            rhs
            $($(, $args)*)?
        )
    }};
}

/// An error of `kind` with a formatted message, as a value: for `ok_or_else` and the like, where
/// `tvm_ffi::bail!` cannot return.
macro_rules! error {
    ($kind:expr, $($message:tt)+) => {
        tvm_ffi::Error::new($kind, &format!($($message)+), "")
    };
}

